/**
 * 任务流.ts —— 左侧上下文侧栏的"步骤"定义。
 *
 * 这是整个外壳的骨架约定（`约定.md` §三 那一句"任务流只换左侧上下文"的落点）：
 *   · 5 个任务步骤 + 2 个底部条目（外观/关于）
 *   · 每一步只是**一个 id + 一句文案键**，具体画什么在 `视图/` 里
 *   · 中区 3D 视口**不属于**任何一步 —— 它常驻（见 `外壳/中区.tsx`）
 *
 * 为什么把这里做成数据而不是写死两个数组：
 *   活动栏、侧栏、键盘快捷键（数字键跳步）都要用同一份顺序，
 *   写两份必然漂移（"加了一步忘了改另一处"是这类外壳最常见的 bug）。
 */
import type { 文案键 } from "../视图/文案";

export type 步骤id =
  | "定义"
  | "规划"
  | "验证"
  | "辨识"
  | "部署"
  | "监控"
  | "诊断"
  | "外观"
  | "关于";

export interface 步骤 {
  id: 步骤id;
  /** 活动栏/侧栏的标题文案键 */
  名键: 文案键;
  /** 悬停说明的文案键 */
  说明键: 文案键;
  /**
   * 归在哪一组：
   *   任务 = 按顺序做设计（定义→规划→验证→辨识→部署）
   *   运行 = 跑起来之后才看的东西（监控）—— 插在任务与底部之间，
   *          因为"监控"不属于设计流程，混进上面会让人以为它是第 6 步
   *   底部 = 设置与信息
   */
  组: "任务" | "运行" | "底部";
}

/** 顺序就是活动栏从上到下的顺序（也决定 Ctrl/Cmd+1..5 的编号） */
export const 步骤表: 步骤[] = [
  { id: "定义", 名键: "步骤.定义", 说明键: "步骤.定义.一句话", 组: "任务" },
  { id: "规划", 名键: "步骤.规划", 说明键: "步骤.规划.一句话", 组: "任务" },
  { id: "验证", 名键: "步骤.验证", 说明键: "步骤.验证.一句话", 组: "任务" },
  { id: "辨识", 名键: "步骤.辨识", 说明键: "步骤.辨识.一句话", 组: "任务" },
  { id: "部署", 名键: "步骤.部署", 说明键: "步骤.部署.一句话", 组: "任务" },
  { id: "监控", 名键: "步骤.监控", 说明键: "步骤.监控.一句话", 组: "运行" },
  { id: "诊断", 名键: "步骤.诊断", 说明键: "步骤.诊断.一句话", 组: "运行" },
  { id: "外观", 名键: "步骤.外观", 说明键: "步骤.外观.一句话", 组: "底部" },
  { id: "关于", 名键: "步骤.关于", 说明键: "步骤.关于.一句话", 组: "底部" },
];

export const 任务步骤 = 步骤表.filter((s) => s.组 === "任务");
export const 运行步骤 = 步骤表.filter((s) => s.组 === "运行");
export const 底部步骤 = 步骤表.filter((s) => s.组 === "底部");

export function 取步骤(id: 步骤id): 步骤 {
  const 找 = 步骤表.find((s) => s.id === id);
  if (!找) throw new Error(`任务流里没有这一步：${id}`);
  return 找;
}
