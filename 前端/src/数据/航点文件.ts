/**
 * 航点文件.ts —— 把用户手里的 CSV/TXT 解析成关节航点。
 *
 * ★ 为什么解析放在**前端**：
 *   浏览器有文件选择器，用户点一下就能选；若放到后端，就得让用户手打路径，
 *   而"路径"这件事在桌面 app 里还牵扯到 TCC 沙箱权限（之前踩过）。
 *   解析是纯函数，放哪都一样 —— 放前端少一层往返、也少一个权限面。
 *
 * ★ 解析规则（必须写在界面上，否则用户不知道该怎么准备文件）：
 *   · 逗号或空格分隔；每行一组关节角
 *   · **跳过**以 `#` `//` 开头的注释行与空行
 *   · 如果有表头（含字母），自动跳过第一行
 *   · 每行的列数必须一致，且 ≥2 列
 *   · 无法解析的数字 → 报出**行号**，不静默丢弃
 */

export interface 解析结果 {
  航点: number[][];
  行数: number;
  列数: number;
  跳过: number;       // 注释/空行数
  问题: string;       // 空串 = 没问题
}

const 数字 = /^[+-]?(\d+\.?\d*|\.\d+)([eE][+-]?\d+)?$/;

export function 解析航点文本(文本: string, 期望列数?: number): 解析结果 {
  const 行们 = 文本.replace(/\r\n?/g, "\n").split("\n");
  const 航点: number[][] = [];
  let 跳过 = 0;
  let 首行是表头 = false;
  let 列数 = 0;

  for (let i = 0; i < 行们.length; i += 1) {
    const 原 = 行们[i].trim();
    if (!原 || 原.startsWith("#") || 原.startsWith("//")) {
      跳过 += 1;
      continue;
    }
    // 分隔符：逗号 / 制表符 / 空白（CSV 与纯文本都吃）
    const 段 = 原.split(/[,\t]+|\s+/).filter((s) => s.length > 0);
    const 全数字 = 段.every((s) => 数字.test(s));
    if (!全数字) {
      // 只允许**第一行**不是数字（当表头），其余必须报错并指出行号
      if (航点.length === 0 && !首行是表头) {
        首行是表头 = true;
        跳过 += 1;
        continue;
      }
      return {
        航点, 行数: 航点.length, 列数: 列数 || 段.length, 跳过,
        问题: `第 ${i + 1} 行有无法解析的内容：「${段.slice(0, 4).join(" ")}」`,
      };
    }
    const 值 = 段.map(Number);
    if (!列数) {
      列数 = 值.length;
      if (列数 < 2) {
        return { 航点, 行数: 0, 列数, 跳过, 问题: `只有 ${列数} 列 —— 关节航点至少 2 列` };
      }
    } else if (值.length !== 列数) {
      return {
        航点, 行数: 航点.length, 列数, 跳过,
        问题: `第 ${i + 1} 行有 ${值.length} 列，前面是 ${列数} 列（列数必须一致）`,
      };
    }
    航点.push(值);
  }

  if (航点.length < 2) {
    return { 航点, 行数: 航点.length, 列数, 跳过, 问题: `只解析出 ${航点.length} 个航点 —— 至少需要 2 个` };
  }
  if (期望列数 !== undefined && 列数 !== 期望列数) {
    return {
      航点, 行数: 航点.length, 列数, 跳过,
      问题: `文件是 ${列数} 列，但当前机器人是 ${期望列数} 个关节`,
    };
  }
  return { 航点, 行数: 航点.length, 列数, 跳过, 问题: "" };
}
