// 连接实例
// ---------------------------------------------------------------------------
export const 后端 = new 连接(猜地址());

export function 起连接(): () => void {
  const 取消 = 后端.订阅((e) => {
    if (e.状态) 换((s) => ({ ...s, 连接: e.状态! }));
    if (e.错误) 换((s) => ({ ...s, 错误: e.错误! }));
    if (e.握手) 换((s) => ({ ...s, 握手: e.握手!, 错误: null }));
    if (e.回执) 换((s) => ({ ...s, 回执: e.回执! }));
    if (e.帧) 收帧(e.帧);
  });
  后端.连();

  const 心跳 = window.setInterval(() => {
    换((s) => ({ ...s, 主题计数: { ...后端.计数 }, 主题速率: { ...后端.速率 } }));
  }, 1000);

  return () => {
    取消();
    window.clearInterval(心跳);
    后端.关();
  };
}

function 收帧(帧: 帧): void {
  const 墙钟 = (帧.墙钟 ?? Date.now() / 1000) as number;
  switch (帧.主题) {
    case "资产库":
      换((s) => ({ ...s, 资产: { 数据: 帧.数据 as 资产库, 帧号: 帧.序号 ?? 0, 墙钟 } }));
      return;
    case "系统":
      换((s) => ({ ...s, 系统: { 数据: 帧.数据 as 系统状态, 帧号: 帧.序号 ?? 0, 墙钟 } }));
      return;
    case "项目状态":
      换((s) => ({ ...s, 项目: { 数据: 帧.数据 as 项目状态, 帧号: 帧.序号 ?? 0, 墙钟 } }));
      return;
    case "模型状态":
      换((s) => ({ ...s, 模型: { 数据: 帧.数据 as 模型状态, 帧号: 帧.序号 ?? 0, 墙钟 } }));
      return;
    case "参数表":
      换((s) => ({
        ...s,
        参数: {
          数据: 帧.数据 as { 参数?: Record<string, 参数项> },
          帧号: 帧.序号 ?? 0,
          墙钟,
        },
      }));
      return;
    case "辨识状态":
      换((s) => ({ ...s, 辨识: { 数据: 帧.数据 as 辨识状态, 帧号: 帧.序号 ?? 0, 墙钟 } }));
      return;
    case "指标": {
      const 数值 = (帧.数据.数值 ?? {}) as Record<string, number>;
      const t = (帧.数据.墙钟 as number) ?? 墙钟;
      if (!Object.keys(数值).length) return;
      换((s) => {
        const 曲线 = { ...s.曲线 };
        for (const [名, v] of Object.entries(数值)) {
          if (typeof v !== "number" || !Number.isFinite(v)) continue;
          const 旧 = 曲线[名] ?? [];
          // 只在"确实新增了一个点"时复制数组，避免每条曲线每帧都重建
          let 新 = 旧.length && 旧[旧.length - 1].t === t
            ? [...旧.slice(0, -1), { t, v }]
            : [...旧, { t, v }];
          新 = 淘汰(新, t);
          曲线[名] = 新;
        }
        return { ...s, 曲线, 曲线总帧: s.曲线总帧 + 1 };
      });
      return;
    }
    default:
      return;
  }
}

function 淘汰(点: 采样点[], 现在: number): 采样点[] {
  let 出 = 点;
  if (出.length > 曲线容量) 出 = 出.slice(出.length - 曲线容量);
  const 最早 = 现在 - 曲线窗口;
  let 起点 = 0;
  while (起点 < 出.length && 出[起点].t < 最早) 起点 += 1;
  if (起点 > 0) 出 = 出.slice(起点);
  return 出;
}

