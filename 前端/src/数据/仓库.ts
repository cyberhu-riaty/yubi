/**
 * 仓库.ts —— 界面状态的唯一来源（P1 的 L0 那一半）
 *
 * 为什么不用 useState 到处传（这是 SPEC 里明确点名不要抄 LE 的地方）：
 *   LE 是"App 一层 10 个 useState + 一个 data prop drilling 下发全部"，
 *   而且那个 data 里混装了三类关注点（规划结果 / 播放时钟 / 机器人资产）。
 *   我们要长到九项功能，那样必然失控。
 *
 * 所以这里按**域**拆开，每个域是一份 latest-wins 快照 + 一段曲线历史：
 *   项目 / 模型 / 参数 / 指标 / 辨识 / 连接
 * 组件用 `用仓库(选择器)` 只订阅自己关心的那一小块，避免"一个字节变了整页重画"。
 *
 * 曲线历史（环形缓冲）单独说明：
 *   指标是 30 Hz 的，一分钟就是 1800 帧 × N 条曲线。全留会吃内存，
 *   所以每条曲线只留最近 `曲线容量` 个点，且**按墙钟时间**淘汰
 *   （用墙钟而不是仿真时间：物理暂停时仿真时间不动，曲线会挤成一坨）。
 */
import { useSyncExternalStore } from "react";
import { 连接, 猜地址, type 回执, type 帧, type 握手, type 连接状态, type 采样点 } from "./连接";

export interface 项目状态 {
  项目?: string;
  模型路径?: string;
  模型显示名?: string;
  算法?: Record<string, unknown>[];
  报告?: string[];
  算法库?: string[];
  已存盘?: boolean;
  控盘?: string;
  被覆盖?: string[];
  重力开?: boolean;
}

/** 资产库里的一台机器人（来自后端 `模型桥.取资产清单()` 的真实产物） */
export interface 资产项 {
  标识?: string;
  显示名?: string;
  类别?: string;
  自由度?: number;
  执行器数?: number;
  许可?: string;
  可控制?: boolean;
  /** 可直接加载的那个文件（= 清单里的「扭矩模型」绝对路径） */
  路径?: string;
}

/** 运行期系统指标（来自 `系统桥`，1 Hz 一条） */
export interface 系统状态 {
  仿真时间?: number;
  墙钟?: number;
  RTF?: number;
  步频?: number;
  仿真步长?: number;
  内存MB?: number;
  插件数?: number;
  出错?: string;
}

export interface 资产库 {
  数量?: number;
  模型?: 资产项[];
}

export interface 模型状态 {
  当前路径?: string;
  当前显示名?: string;
  自由度?: number;
  执行器数?: number;
  状态?: string;
  耗时?: number;
}

/**
 * 一个可调参数。
 * ★ 形状来自后端 `参数桥.采集可调参数()` 的真实产物 —— 不是想象的。
 *   （早先这里写的是 `{值, 最小, 最大}`，与实现不符，导致 `范围` 数组被当对象渲染成乱码。）
 */
export interface 参数项 {
  插件?: string;
  插件英文?: string;
  插件版本?: string;
  参数?: string;
  值?: number;
  /** [最小, 最大] —— 注意是**数组**，不是两个字段 */
  范围?: number[];
  步长?: number;
  单位?: string;
  [键: string]: unknown;
}

export interface 辨识状态 {
  状态?: string;
  进度?: string;
  采样步数?: number;
  结果?: Record<string, unknown>[];
  拟合?: Record<string, unknown>;
  耗时?: number;
  日志?: string[];
}

export interface 快照域<T> {
  数据: T | null;
  帧号: number;
  墙钟: number;
}

export interface 界面状态 {
  连接: 连接状态;
  错误: string | null;
  握手: 握手 | null;
  主题计数: Record<string, number>;
  主题速率: Record<string, number>;
  项目: 快照域<项目状态>;
  模型: 快照域<模型状态>;
  /** 可选模型清单。★ 与 `模型` 区分：那是"当前装的哪台"，这是"能选哪些" */
  资产: 快照域<资产库>;
  /** 运行期系统指标（RTF/步频/内存）。只在仿真侧能量到的量在这里 */
  系统: 快照域<系统状态>;
  /**
   * 参数表。★ 负载形状是 `{参数: {全名: 参数项}}` —— 外面还包着一层 `参数`。
   * 这里如实声明，别在类型上"美化"成扁平结构：类型与实现对不上时，
   * 错的是类型（实测踩过：少剥一层导致表格渲染出一堆 `--` 行）。
   */
  参数: 快照域<{ 参数?: Record<string, 参数项> }>;
  辨识: 快照域<辨识状态>;
  /** {曲线名: 采样点[]} —— 只留最近 N 个点 */
  曲线: Record<string, 采样点[]>;
  曲线总帧: number;
  回执: 回执 | null;
}

/** 每条曲线保留的最大点数（30 Hz × 120 秒 = 3600；曲线一多就很占内存） */
const 曲线容量 = 3600;
/** 曲线保留的墙钟窗口（秒） */
const 曲线窗口 = 120;

const 空快照 = { 数据: null, 帧号: 0, 墙钟: 0 };

let 状态: 界面状态 = {
  连接: "连接中",
  错误: null,
  握手: null,
  主题计数: {},
  主题速率: {},
  项目: { ...空快照 },
  模型: { ...空快照 },
  资产: { ...空快照 },
  系统: { ...空快照 },
  参数: { ...空快照 },
  辨识: { ...空快照 },
  曲线: {},
  曲线总帧: 0,
  回执: null,
};

const 订阅者 = new Set<() => void>();
let 版本号 = 0;
let 通知排队 = false;

function 换(改: (草稿: 界面状态) => 界面状态): void {
  状态 = 改(状态);
  版本号 += 1;
  // 合帧：一秒钟可能有上百条消息，不能让每条都触发一次 React 渲染
  if (通知排队) return;
  通知排队 = true;
  requestAnimationFrame(() => {
    通知排队 = false;
    for (const f of 订阅者) f();
  });
}

export function 取状态(): 界面状态 {
  return 状态;
}

export function 用仓库<T>(选择器: (s: 界面状态) => T): T {
  return useSyncExternalStore(
    (回调) => {
      订阅者.add(回调);
      return () => 订阅者.delete(回调);
    },
    () => 选择器(取状态()),
    () => 选择器(取状态()),
  );
}

