/* ---------------------------------------------------------------------------
 * 调试钩子：把仓库暴露到 window，供自动化测试读取真实内部状态。
 *
 * 为什么必须有它：端到端测试若靠"正则去匹配页面上的数字"，会随排版微调而失效
 * （实测踩过：换成"点数在长大"的判定后仍然取到了无关的数字）。
 * 把状态直接暴露出来，测试问的就是"界面真的收到了多少帧曲线数据"，
 * 而不是"我猜页面上哪个数字是点数"。
 *
 * 只在浏览器环境挂载，不加任何运行时开销；生产打包同样保留（无副作用）。
 * ------------------------------------------------------------------------- */
declare global {
  interface Window {
    驭臂?: {
      取状态: typeof 取状态;
      曲线点数: () => number;
      曲线名: () => string[];
    };
  }
}

if (typeof window !== "undefined") {
  window.驭臂 = {
    取状态,
    曲线点数: () =>
      Object.values(取状态().曲线).reduce((合计, 点们) => 合计 + 点们.length, 0),
    曲线名: () => Object.keys(取状态().曲线).sort(),
  };
}
