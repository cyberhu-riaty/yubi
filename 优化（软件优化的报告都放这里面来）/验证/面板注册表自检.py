"""面板注册表语义自检（不需要开窗口）：验证"标签条开关 / 老状态迁移 / 展开与钉住 / F9 / 重置版面"。

用法：./.venv/bin/python "优化（软件优化的报告都放这里面来）/验证/面板注册表自检.py"

★ 侧栏版（v2 契约）与旧页签版（v1）的三个关键差别，都在下面的用例里钉住：
  ① 「容器可见」→「标签条可见」；「弹出」这个概念**取消**，面板只有三态：收起/临时展开/钉住
  ② 「弹出」**不迁移**成钉住 —— 否则用户一开软件就有面板压着 3D（默认零遮挡是硬要求）
  ③ `独立窗口 = True` 的面板（展示=物理总闸 / 外观）不受标签条开关连坐
"""
from __future__ import annotations

import importlib
import json
import os
import sys
import tempfile

包根 = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
面板目录 = os.path.join(包根, "软件", "面板")
for p in (os.path.join(包根, "软件"), 面板目录):
    if p not in sys.path:
        sys.path.insert(0, p)

状态文件 = os.path.join(包根, "输出", "面板.json")
老状态文件 = os.path.join(包根, "输出", "面板状态.json")
备份 = {}


def 读路径(路径):
    try:
        with open(路径, encoding="utf-8") as f:
            return f.read()
    except FileNotFoundError:
        return None


def 写路径(路径, 文本):
    os.makedirs(os.path.dirname(路径), exist_ok=True)
    with open(路径, "w", encoding="utf-8") as f:
        f.write(文本)


def 还原():
    for 路径, 内容 in 备份.items():
        if 内容 is None:
            if os.path.exists(路径):
                os.remove(路径)
        else:
            写路径(路径, 内容)


class 假面板:
    def __init__(self, 名, 独立窗口=False):
        self.面板显示名 = 名
        self.独立窗口 = 独立窗口
        self.可见 = False


class 侧栏面板:                     # 假的侧栏：只为让 注册.有容器() 认出来（按类名判断）
    def __init__(self):
        self.面板显示名 = "侧栏"
        self.可见 = True


def 重载():
    import 面板注册表
    模块 = importlib.reload(面板注册表)
    模块.重置缓存()          # 自检要反复换状态文件验证，所以每次重载都清一遍内存状态
    return 模块


def 用例(说明, 条件, 细节=""):
    print(f"  {'✓' if 条件 else '✗'} {说明}" + (f"   [{细节}]" if 细节 and not 条件 else ""))
    return bool(条件)


def main() -> int:
    print("=" * 74)
    print("  面板注册表 语义自检（侧栏版：标签条 / 迁移 / 展开与钉住 / F9 / 重置版面）")
    print("=" * 74)
    备份[状态文件] = 读路径(状态文件)
    备份[老状态文件] = 读路径(老状态文件)
    通过 = 0
    总数 = 0
    try:
        # ---- ① 标签条开关 → 面板可见性（不再有「某个面板被永久关掉」这回事）----
        print("\n① 标签条开关 → 面板可见性；独立窗口的面板不被连坐")
        写路径(状态文件, json.dumps({"版本": 2, "标签条可见": False, "钉住": {}}, ensure_ascii=False))
        注册 = 重载()
        甲, 乙 = 假面板("模型库"), 假面板("实时监控")
        展示 = 假面板("展示", 独立窗口=True)
        注册.每帧(甲)
        注册.每帧(乙)
        注册.每帧(展示)
        总数 += 2
        通过 += 用例("标签条收起 → 名册里的面板不可见", 甲.可见 is False and 乙.可见 is False)
        通过 += 用例("独立窗口的面板照样可见（物理总闸不能被藏）", 展示.可见 is True)
        注册.全部显示()
        总数 += 2
        通过 += 用例("F9（全部显示）→ 标签条显示", 注册.标签条可见() is True)
        通过 += 用例("F9 之后面板都可见", 甲.可见 is True and 乙.可见 is True)

        # ---- ② 老状态文件迁移：老版把所有面板都关了 → 标签条默认收起 ----
        print("\n② 老版状态迁移（老文件里面板全关 = 用户想清屏 → 标签条默认收起）")
        if os.path.exists(状态文件):
            os.remove(状态文件)
        写路径(老状态文件, json.dumps({"关于": False, "外观": False, "模型库": False},
                                    ensure_ascii=False))
        注册 = 重载()
        注册.每帧(假面板("外观"))
        总数 += 1
        通过 += 用例("老文件全关 → 标签条收起", 注册.标签条可见() is False)
        if os.path.exists(状态文件):
            os.remove(状态文件)
        写路径(老状态文件, json.dumps({"关于": False, "外观": True}, ensure_ascii=False))
        注册 = 重载()
        注册.每帧(假面板("外观"))
        总数 += 1
        通过 += 用例("老文件里有开着的 → 标签条显示", 注册.标签条可见() is True)

        # ---- ③ v1 存档容错：容器可见 → 标签条可见；弹出/当前页签**不迁移** ----
        print("\n③ v1 存档（容器可见 / 弹出 / 当前页签）读进来不炸、且不迁移成钉住")
        写路径(状态文件, json.dumps({"容器可见": False, "当前页签": "外观",
                                    "弹出": {"模型库": True}}, ensure_ascii=False))
        注册 = 重载()
        注册.每帧(假面板("模型库"))
        总数 += 3
        通过 += 用例("v1「容器可见=False」→ 标签条收起", 注册.标签条可见() is False)
        通过 += 用例("v1「弹出」不迁移成钉住（否则一开软件就压着 3D）", 注册.钉住集合() == [])
        通过 += 用例("v1「当前页签」不迁移成上次展开", 注册.上次展开() == "")

        # ---- ④ 临时展开 / 钉住 / 收起全部 ----
        print("\n④ 临时展开与钉住（同一时刻只有一个临时展开；钉住常驻）")
        注册 = 重载()
        注册.设标签条可见(True)          # ③ 故意把标签条设成收起，这里要先恢复显示
        侧栏 = 侧栏面板()
        注册.每帧(侧栏)
        面板 = 假面板("模型库")
        算法 = 假面板("算法")
        注册.每帧(面板)
        注册.每帧(算法)
        总数 += 1
        通过 += 用例("侧栏已登记（有容器() 为真）", 注册.有容器() is True)
        注册.设展开("模型库")
        总数 += 2
        通过 += 用例("设展开后 展开中() 是它", 注册.展开中() == "模型库")
        通过 += 用例("展开中的面板由侧栏画（自己不开窗口）", 注册.画在容器里(面板) is True,
                    f"标签条={注册.标签条可见()} 有容器={注册.有容器()} "
                    f"分栏={注册.分栏('模型库')!r} 独立窗口={getattr(面板, '独立窗口', None)}")
        注册.设展开("算法")
        总数 += 1
        通过 += 用例("换一个展开 → 前一个自动不是展开中", 注册.展开中() == "算法")
        注册.切换展开("算法")
        总数 += 1
        通过 += 用例("点同一个标签 = 收起", 注册.展开中() == "")
        注册.切换展开("模型库")
        注册.设钉住(面板, True)
        总数 += 2
        通过 += 用例("钉住 → 是钉住() 为真", 注册.是钉住(面板) is True)
        通过 += 用例("钉住的也算展开中", 注册.是展开中(面板) is True)
        注册.收起全部()
        总数 += 2
        通过 += 用例("收起全部：临时展开清空", 注册.展开中() == "")
        通过 += 用例("收起全部：钉住保留", 注册.是钉住(面板) is True)
        注册.收起全部(保留钉住=False)
        总数 += 1
        通过 += 用例("收起全部(保留钉住=False)：钉住也清掉", 注册.钉住集合() == [])

        # ---- ⑤ 名单与"不在名单里的面板" ----
        print("\n⑤ 名册：左右分组、不在名单里的面板必须自己开窗口（不许两头都不画）")
        注册 = 重载()
        注册.设标签条可见(True)
        注册.每帧(侧栏面板())
        for 名 in ("模型库", "算法", "控制器参数", "参数辨识", "实时监控", "数据录制", "关于", "野面板"):
            注册.每帧(假面板(名))
        总数 += 4
        通过 += 用例("侧栏已登记（有容器() 为真）", 注册.有容器() is True)
        通过 += 用例("侧栏顺序 = 左4 + 右3（野面板排在最后）",
                    注册.侧栏顺序()[:7] == ["模型库", "算法", "控制器参数", "参数辨识",
                                            "实时监控", "数据录制", "关于"]
                    and 注册.侧栏顺序()[-1] == "野面板", str(注册.侧栏顺序()))
        通过 += 用例("不在名单里的面板：不归侧栏画（让它自己开窗口）",
                    注册.画在容器里(假面板("野面板")) is False)
        通过 += 用例("名单里的面板：归侧栏画", 注册.画在容器里(假面板("模型库")) is True)

        # ---- ⑥ 存档 v2 结构：不许再出现"某个面板被关掉"的记录 ----
        print("\n⑥ 状态文件升到 v2（不再记「面板被关掉」）")
        注册.设钉住("模型库", True)
        注册.设展开("算法")
        文本 = 读路径(状态文件) or ""
        数据 = json.loads(文本) if 文本.strip().startswith("{") else {}
        总数 += 3
        通过 += 用例("存档里有 版本=2", 数据.get("版本") == 2, 文本[:80])
        通过 += 用例("存档里有 标签条可见", "标签条可见" in 数据)
        通过 += 用例("钉住表里只有 true（没有「被关掉」这种记录）",
                    all(bool(v) for v in (数据.get("钉住") or {}).values()))

        # ---- ⑦ 存档里的陌生名字（面板改名/删掉）必须容错 ----
        print("\n⑦ 存档里出现已经不存在面板名 → 不崩、不生效")
        写路径(状态文件, json.dumps({"版本": 2, "标签条可见": True,
                                    "钉住": {"早就没有的面板": True}, "上次展开": "也不存在"},
                                   ensure_ascii=False))
        注册 = 重载()
        炸了 = ""
        try:
            注册.每帧(假面板("模型库"))
        except Exception as 异常:                                            # noqa: BLE001
            炸了 = f"{type(异常).__name__}: {异常}"
        总数 += 2
        通过 += 用例("带陌生名字的存档不会让它崩", 炸了 == "", 炸了)
        通过 += 用例("陌生钉住名不进钉住集合", 注册.钉住集合() == [], str(注册.钉住集合()))

        # ---- ⑧ 重置版面：只清我们自己的窗口记录，不动官方布局 ----
        print("\n⑧ 重置版面（清理 ~/.mujoco.ini 里我们这些窗口的记录）")
        ini = os.path.join(tempfile.mkdtemp(), "fake.ini")
        写路径(ini, "\n".join([
            "[Window][Dockspace]", "Pos=0,22", "Size=1200,746", "",
            "[Window][Options]", "Pos=0,22", "DockId=0x00000001,0", "",
            "[Window][Model library]", "Pos=12,56", "Size=360,460", "DockId=0x00000009,0", "",
            "[Window][Appearance]", "Pos=341,189", "DockId=0x00000009,1", "",
            "[Window][Workbench]", "Pos=323,233", "Size=765,448", "DockId=0x0000000A,0", "",
            "[Window][About]", "Pos=162,262", "Size=325,776", "",
            "[Docking][Data]", "DockNode ID=0x00000009 Pos=341,189 Size=486,387", "",
            "[Studio][UX]", "theme=1", ""]))
        注册._IMGUI配置 = ini
        注册._清理ini()
        剩下 = 读路径(ini) or ""
        总数 += 7
        通过 += 用例("我们自己的窗口段被删掉（Model library）", "[Window][Model library]" not in 剩下)
        通过 += 用例("我们自己的窗口段被删掉（Appearance）", "[Window][Appearance]" not in 剩下)
        通过 += 用例("旧版页签容器的段也清掉（Workbench）", "[Window][Workbench]" not in 剩下)
        通过 += 用例("官方窗口段保留（Options）", "[Window][Options]" in 剩下)
        通过 += 用例("残留的 DockId 行被清掉", "DockId" not in 剩下)
        # ★ 这两条是回归防线：第一版清理把"跳过"标志一直带下去，把删掉的窗口**之后**
        #   的所有段落都吞了（官方停靠布局 [Docking][Data] 与主题 [Studio][UX] 全没）。
        通过 += 用例("官方停靠数据保留（[Docking][Data]）", "[Docking][Data]" in 剩下)
        通过 += 用例("主题设置保留（[Studio][UX] / theme=1）",
                    "[Studio][UX]" in 剩下 and "theme=1" in 剩下)
    finally:
        还原()

    print("\n" + "=" * 74)
    print(f"  结果：{通过}/{总数} 项通过")
    print("=" * 74)
    return 0 if 通过 == 总数 else 1


if __name__ == "__main__":
    raise SystemExit(main())
