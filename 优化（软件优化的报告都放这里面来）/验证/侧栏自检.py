"""侧栏几何与状态判定自检（不需要开窗口）：验证标签条/展开面板的算法与"该不该自动收起"。

用法：./.venv/bin/python "优化（软件优化的报告都放这里面来）/验证/侧栏自检.py"

★ 为什么这些必须是**纯函数**：侧栏的定位每帧都要算，一旦写死在窗口绘制里，
  就只能靠"开窗肉眼看"来验证；抽成纯函数后，"3D 区变了 / 窗口被拉小 / 第一帧没几何"
  这些边界都能在终端里一条条钉住。
"""
from __future__ import annotations

import os
import sys

包根 = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
面板目录 = os.path.join(包根, "软件", "面板")
for p in (os.path.join(包根, "软件"), 面板目录):
    if p not in sys.path:
        sys.path.insert(0, p)

import 侧栏                                                          # noqa: E402

通过 = 0
失败 = 0

# 实测的官方 3D 区（窗口 1200×828 时）
三D = (296.0, 22.0, 678.0, 746.0)


def 用例(名: str, 条件: bool, 说明: str = "") -> None:
    global 通过, 失败
    if 条件:
        通过 += 1
        print(f"  ✓ {名}")
    else:
        失败 += 1
        print(f"  ✗ {名}{('  —— ' + 说明) if 说明 else ''}")


def 矩形约等(甲, 乙, 容差: float = 1e-6) -> bool:
    return len(甲) == len(乙) and all(abs(float(a) - float(b)) <= 容差 for a, b in zip(甲, 乙))


def 主() -> int:
    print("侧栏几何与状态判定自检")

    # ---- ① 标签条（26px，贴在 3D 区内侧）----
    用例("左标签条 = (296,22,26,746)",
         矩形约等(侧栏.算标签条矩形(三D, "左"), (296.0, 22.0, 26.0, 746.0)),
         str(侧栏.算标签条矩形(三D, "左")))
    用例("右标签条贴 3D 右内侧 = (948,22,26,746)",
         矩形约等(侧栏.算标签条矩形(三D, "右"), (948.0, 22.0, 26.0, 746.0)),
         str(侧栏.算标签条矩形(三D, "右")))
    用例("侧别写错时回零矩形（不抛异常）",
         矩形约等(侧栏.算标签条矩形(三D, "中"), (0.0, 0.0, 0.0, 0.0)))

    # ---- ② 展开面板（300 宽、高 min(600, 3D高-16)、顶部 +8）----
    用例("左展开面板 = (322,30,300,600)",
         矩形约等(侧栏.算展开面板矩形(三D, "左"), (322.0, 30.0, 300.0, 600.0)),
         str(侧栏.算展开面板矩形(三D, "左")))
    用例("右展开面板 = (648,30,300,600)",
         矩形约等(侧栏.算展开面板矩形(三D, "右"), (648.0, 30.0, 300.0, 600.0)),
         str(侧栏.算展开面板矩形(三D, "右")))
    用例("矮视口：高跟着 3D 高缩（400 → 384）",
         矩形约等(侧栏.算展开面板矩形((296.0, 22.0, 678.0, 400.0), "左"),
                  (322.0, 30.0, 300.0, 384.0)))
    用例("极窄视口：宽不为负",
         侧栏.算展开面板矩形((296.0, 22.0, 40.0, 746.0), "左")[2] >= 60.0,
         str(侧栏.算展开面板矩形((296.0, 22.0, 40.0, 746.0), "左")))
    左 = 侧栏.算展开面板矩形(三D, "左")
    右 = 侧栏.算展开面板矩形(三D, "右")
    用例("两侧同时展开不重叠", 左[0] + 左[2] <= 右[0], f"左到 {左[0] + 左[2]}，右起 {右[0]}")

    # ---- ③ 拿到几何没有（第一帧 configure_docking_layout 还没被调）----
    用例("零几何 → 不画", 侧栏.能画吗((0.0, 0.0, 0.0, 0.0)) is False)
    用例("正常几何 → 画", 侧栏.能画吗(三D) is True)
    用例("3D 区太窄（120）→ 不画", 侧栏.能画吗((296.0, 22.0, 120.0, 746.0)) is False)
    用例("3D 区太矮（120）→ 不画", 侧栏.能画吗((296.0, 22.0, 678.0, 120.0)) is False)

    # ---- ④ 该不该自动收起（0.8 秒宽限；钉住/鼠标还在/从没移出过 → 不收）----
    用例("移出 0.9 秒 → 收起", 侧栏.该自动收起(False, False, 100.0, 100.9) is True)
    用例("移出 0.5 秒 → 还不收", 侧栏.该自动收起(False, False, 100.0, 100.5) is False)
    用例("恰好 0.8 秒 → 收", 侧栏.该自动收起(False, False, 100.0, 100.8) is True)
    用例("钉住 → 永不收", 侧栏.该自动收起(False, True, 100.0, 9999.0) is False)
    用例("鼠标还在面板上 → 不收", 侧栏.该自动收起(True, False, 100.0, 9999.0) is False)
    用例("从没移出过（时刻 0）→ 不收", 侧栏.该自动收起(False, False, 0.0, 9999.0) is False)

    # ---- ⑤ 左右分组名单 ----
    用例("左栏 4 格（操作类）", 侧栏.左栏 == ("模型库", "算法", "控制器参数", "参数辨识"), str(侧栏.左栏))
    用例("右栏 3 格（观测类）", 侧栏.右栏 == ("实时监控", "数据录制", "关于"), str(侧栏.右栏))
    用例("两侧不重复", not (set(侧栏.左栏) & set(侧栏.右栏)))
    用例("短名表覆盖所有格子",
         all(名 in 侧栏.短名 for 名 in 侧栏.左栏 + 侧栏.右栏),
         str([名 for 名 in 侧栏.左栏 + 侧栏.右栏 if 名 not in 侧栏.短名]))

    print(f"\n结果：{通过} 通过 / {失败} 失败")
    return 1 if 失败 else 0


if __name__ == "__main__":
    sys.exit(主())
