_typescript_type = {
    "number": "number",
    "string": "string",
    "boolean": "boolean",
    "any": "unknown",
    "number[]": "number[]",
    "string[]": "string[]",
    "object[]": "Record<string, unknown>[]",
    "record<number>": "Record<string, number>",
    "record<any>": "Record<string, unknown>",
}


def generate_contract_typescript() -> str:
    import contract

    data = contract.to_dict()
    legacy_class_names = {
        "辨识状态": "IdentificationState", "连接状态": "DeviceConnectionState",
        "告警消息": "AlertSnapshot", "部署状态": "DeploymentState",
        "诊断报告": "DiagnosticReport", "部署命令": "DeploymentCommand",
        "诊断命令": "DiagnosticCommand", "连接命令": "DeviceCommand",
        "高亮命令": "HighlightJointCommand", "辨识命令": "IdentificationCommand",
        "录制命令": "RecordingCommand",
    }
    line = [
        "// Generated by 工具/generate_frontend_assets.py. Do not edit.",
        "// Source: 软件/contract.py. Topic values and quoted legacy fields preserve wire v21.",
        f"export const CONTRACT_VERSION = {data['版本']};",
        f"export const PROTOCOL_VERSION = {contract.VERSION};", "",
    ]

    def type_name(topic: dict, prefix: str) -> str:
        class_name = legacy_class_names.get(topic["类名"], topic["类名"])
        if not class_name.isascii() or not class_name.isidentifier():
            raise ValueError(f"Missing English type name for {topic['类名']!r}")
        return prefix + class_name

    def section(topics: list[dict], prefix: str) -> None:
        line.append(f"export type {prefix}Topic =")
        for topic in topics:
            line.append(f'  | {json.dumps(topic["名"], ensure_ascii=False)}')
        line.extend(["  ;", ""])
        for topic in topics:
            line.append(f"/** {topic['摘要']} */")
            line.append(f"export interface {type_name(topic, prefix)} {{")
            if not topic["字段"]:
                line.append("  [key: string]: unknown;")
            for field in topic["字段"]:
                if field["说明"]:
                    line.append(f"  /** {field['说明']} */")
                annotation = _typescript_type.get(field["类型"], "unknown")
                line.append(f"  {_safe_field(field['名'])}: {annotation};")
            line.extend(["}", ""])
        line.append(f"export interface {prefix}Payloads {{")
        for topic in topics:
            line.append(f'  {json.dumps(topic["名"], ensure_ascii=False)}: {type_name(topic, prefix)};')
        line.extend(["}", ""])

    section(data["下行"], "Server")
    section(data["上行"], "Client")
    line.extend([
        "export interface TopicMetadata {", "  name: string;", "  className: string;",
        "  kind: string;", "  summary: string;", "}", "",
    ])
    for direction, variable in (("下行", "serverTopics"), ("上行", "clientTopics")):
        line.append(f"export const {variable}: TopicMetadata[] = [")
        for topic in data[direction]:
            line.append("  " + json.dumps({
                "name": topic["名"], "className": topic["类名"],
                "kind": topic["种类"], "summary": topic["摘要"],
            }, ensure_ascii=False) + ",")
        line.extend(["];", ""])
    return "\n".join(line)


def _safe_field(name: str) -> str:
    """Quote legacy wire field keys; they are transport data, not code identifiers."""
    if name.isascii() and name.isidentifier():
        return name
    return json.dumps(name, ensure_ascii=False)


