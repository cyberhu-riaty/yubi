def get_color(colors: dict, keys: tuple[str, ...]) -> str | None:
    for k in keys:
        if k in colors:
            return str(colors[k])
    return None


def theme_table_path() -> str:
    """New ASCII name first; accept the historical file name for old checkouts."""
    for name in ("theme_table.json", "风格表.json"):
        path = os.path.join(SOFTWARE_DIR, name)
        if os.path.exists(path):
            return path
    raise FileNotFoundError("theme_table.json")


def generate_theme_css() -> str:
    table = json.load(open(theme_table_path(), encoding="utf-8"))
    themes: dict = table["themes"]
    line: list[str] = [
        "/* ⚠️ 本文件由 `工具/generate_frontend_assets.py` 生成，**不要手改**。",
        " * 来源：`软件/theme_table.json`（全部风格，数据驱动换肤的唯一数据源）。",
        " * 用法：把 `data-theme=\"mission_control\"` 放在 <html> 上即可整站换肤。 */",
        "",
        ":root {",
        "  --radius: 6px;",
        "  --font-ui: -apple-system, BlinkMacSystemFont, \"PingFang SC\", \"Microsoft YaHei\",",
        "             \"Segoe UI\", Roboto, sans-serif;",
        "  --font-mono: \"SF Mono\", ui-monospace, Menlo, Consolas, monospace;",
        "}",
        "",
    ]
    # 默认皮肤 id：来自 `theme_table.json` 的 `default_theme` 字段（取不到就退回排序第一个）
    default_theme = table.get("default_theme") or None
    # ★ 默认皮肤必须**先输出**，其余皮肤后输出。
    #   原因：默认块带 `:root`，而 `:root` 与 `[data-theme=…]` 同特异性；
    #   若默认块排在最后，它会在 `<html data-theme="mission_control">` 时仍然覆盖所有
    #   皮肤变量 —— 换肤看起来"点了没反应"（实测踩到）。
    #   排到最前面后：没设 data-theme → `:root` 生效；设了 → 后面的属性块覆盖。
    order = list(themes.items())
    if default_theme in themes:
        order = [(default_theme, themes[default_theme])] + [
            (name, theme) for name, theme in order if name != default_theme
        ]
    for i, (name, theme) in enumerate(order):
        color = theme.get("colors", {})
        style = theme.get("styles", {})
        plot = theme.get("plots", {})
        imp = plot.get("implot", {}) if isinstance(plot, dict) else {}
        palette = plot.get("palette", []) if isinstance(plot, dict) else []
        # ★ 选择器不能都挂 `:root`：那样 5 套风格会互相覆盖，只有最后一套生效
        #   （实测踩过）。默认那套挂 `:root`（没设 data-theme 时也能看），
        #   其余只挂属性选择器。
        # ★ 默认皮肤由 `theme_table.json` 的 `default_theme` 字段决定，**不再靠列表排序**。
        #   靠排序的话，"想换个默认皮肤"就得去挪数据顺序 —— 那会连带改掉
        #   `themes.ts` 的顺序，界面上皮肤列表也跟着跳，属于用错了杠杆。
        default = (name == default_theme) or (default_theme is None and i == 0)
        selector = (':root, [data-theme="%s"]' % name) if default else ('[data-theme="%s"]' % name)
        line.append(f"/* {theme.get('display_name', name)} · {theme.get('english_name','')}"
                    f" —— {theme.get('tagline','')} */")
        line.append(f"{selector} {{")
        for semantic, keys in SEMANTIC_COLORS.items():
            value = get_color(color, keys)
            if value:
                line.append(f"  --{semantic}: {value};")
        for semantic, key in PLOT_COLORS.items():
            if key in imp:
                line.append(f"  --{semantic}: {imp[key]};")
        if palette:
            line.append("  --palette: " + ", ".join(palette) + ";")
            for i, c in enumerate(palette[:8], 1):
                line.append(f"  --palette-{i}: {c};")
        # 语义状态色：日志等级、兼容性提示、运行状态共用。
        #   ★ 单独放在风格表顶层的 `网页语义色` 里，而不是从调色板里猜索引 ——
        #     调色板的顺序是给曲线用的，拿它当状态色会在换肤后把"错误"画成紫色。
        semantic_colors = table.get("web_semantic_colors", {}).get(name, {})
        for semantic in ("info", "ok", "warn", "danger"):
            value = semantic_colors.get(semantic)
            if value:
                line.append(f"  --{semantic}: {value};")
        # 样式：只搬网页有意义的几项
        roundness = style.get("FrameRounding")
        border = style.get("WindowBorderSize")
        inner = style.get("WindowPadding")
        if isinstance(roundness, (int, float)):
            line.append(f"  --radius: {float(roundness):.1f}px;")
        if isinstance(border, (int, float)):
            line.append(f"  --border-w: {float(border):.1f}px;")
        if isinstance(inner, list) and len(inner) == 2:
            line.append(f"  --pad-x: {float(inner[0]):.1f}px;")
            line.append(f"  --pad-y: {float(inner[1]):.1f}px;")
        line.append(f"  --base-theme: {theme.get('base_theme','dark')};")
        line.append(f"  --font-scale: {theme.get('panel_font_scale', 1.0)};")
        line.append("}")
        # 深浅色提示：给浏览器原生控件（滚动条、输入框）用。
        # ★ 默认那套要连 `:root` 一起写，否则"没设 data-theme"时拿不到 color-scheme。
        palette_name = "light" if theme.get("base_theme") == "light" else "dark"
        line.append((f':root, [data-theme="{name}"]' if default else f'[data-theme="{name}"]')
                 + f" {{ color-scheme: {palette_name}; }}")
        line.append("")
    return "\n".join(line)


# ---------------------------------------------------------------------------
# ③ 主题元信息 → TS（前端风格切换器要用）
# ---------------------------------------------------------------------------
def generate_theme_typescript() -> str:
    table = json.load(open(theme_table_path(), encoding="utf-8"))
    line = [
        "// Generated by 工具/generate_frontend_assets.py. Do not edit.",
        "// Source: 软件/theme_table.json.",
        "export interface ThemeMetadata {", "  id: string;", "  name: string;", "  legacyName: string;",
        "  englishName: string;",
        "  description: string;", "  baseTheme: string;", "}", "",
        "export const themes: ThemeMetadata[] = [",
    ]
    for name, theme in table["themes"].items():
        line.append("  " + json.dumps({
            "id": name, "name": theme.get("display_name", name),
            "legacyName": theme.get("legacy_name", ""),
            "englishName": theme.get("english_name", ""),
            "description": theme.get("tagline", ""), "baseTheme": theme.get("base_theme", "dark"),
        }, ensure_ascii=False) + ",")
    default_theme = table.get("default_theme") or table["theme_order"][0]
    line.extend(["];", "", "export const DEFAULT_THEME = " + json.dumps(default_theme, ensure_ascii=False) + ";", ""])
    return "\n".join(line)


