def 新页(prs, 标题: str, 副标题: str = "") -> object:
    页 = prs.slides.add_slide(prs.slide_layouts[6])
    背景 = 页.shapes.add_shape(MSO_SHAPE.RECTANGLE, 0, 0, W, H)
    背景.fill.solid()
    背景.fill.fore_color.rgb = 底
    背景.line.fill.background()
    背景.shadow.inherit = False

    # 左侧品牌竖条
    条 = 页.shapes.add_shape(MSO_SHAPE.RECTANGLE, 0, 0, Inches(0.07), H)
    条.fill.solid()
    条.fill.fore_color.rgb = 强调
    条.line.fill.background()
    条.shadow.inherit = False

    框 = 页.shapes.add_textbox(Inches(0.55), Inches(0.30), Inches(12.2), Inches(0.62))
    p = 框.text_frame.paragraphs[0]
    r = p.add_run()
    r.text = 标题
    r.font.size = Pt(27)
    r.font.bold = True
    r.font.color.rgb = 主文
    r.font.name = 字体
    if 副标题:
        框2 = 页.shapes.add_textbox(Inches(0.58), Inches(0.92), Inches(12.2), Inches(0.4))
        p2 = 框2.text_frame.paragraphs[0]
        r2 = p2.add_run()
        r2.text = 副标题
        r2.font.size = Pt(12.5)
        r2.font.color.rgb = 次文
        r2.font.name = 字体
    线 = 页.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(0.55), Inches(1.28),
                           Inches(12.2), Emu(9525))
    线.fill.solid()
    线.fill.fore_color.rgb = 描边
    线.line.fill.background()
    线.shadow.inherit = False
    return 页


def 写框(页, 左, 上, 宽, 高, 行们, 行距: float = 1.0) -> None:
    """行们 = [(文本, 字号, 颜色, 是否加粗, 缩进级别), …]"""
    框 = 页.shapes.add_textbox(左, 上, 宽, 高)
    体 = 框.text_frame
    体.word_wrap = True
    体.margin_left = 体.margin_right = Inches(0.02)
    体.margin_top = 体.margin_bottom = 0
    for i, (文本, 号, 色, 粗, 缩进) in enumerate(行们):
        p = 体.paragraphs[0] if i == 0 else 体.add_paragraph()
        p.alignment = PP_ALIGN.LEFT
        p.line_spacing = 行距
        p.space_after = Pt(3)
        if 缩进:
            p.level = min(缩进, 4)
        r = p.add_run()
        r.text = 文本
        r.font.size = Pt(号)
        r.font.color.rgb = 色
        r.font.bold = 粗
        r.font.name = 字体


def 卡片(页, 左, 上, 宽, 高, 标题: str, 行们, 标题色=强调) -> None:
    盒 = 页.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, 左, 上, 宽, 高)
    盒.fill.solid()
    盒.fill.fore_color.rgb = 面板
    盒.line.color.rgb = 描边
    盒.line.width = Pt(0.75)
    盒.shadow.inherit = False
    盒.adjustments[0] = 0.06
    行 = [(标题, 13, 标题色, True, 0)] + 行们
    写框(页, 左 + Inches(0.16), 上 + Inches(0.11), 宽 - Inches(0.32),
        高 - Inches(0.22), 行, 行距=1.05)


def 图(页, 路径: str, 左, 上, 宽=None, 高=None) -> None:
    """放图。宽高给哪个就以哪个为准 —— ★ 只给宽度会在不知道原图比例时冲出页面底部
    （几何检查抓过这个：2400×1656 的截图给 width=5.6in，高度就 3.86in，整页溢出）。"""
    if not os.path.exists(路径):
        return
    if 高 is not None:
        页.shapes.add_picture(路径, 左, 上, height=高)
    else:
        页.shapes.add_picture(路径, 左, 上, width=宽)


