"""
重力桥.py —— 【Display】面板的"关掉重力 / 回到默认姿态"通道

它解决什么问题（用户原话）：
    "模型刚加载的时候就受到重力影响往下掉。如果在纯展示的时候（即没有加载控制算法），
     在界面的左上角设计一个小方框，勾选的时候展示模型的默认姿态（即无重力影响），
     没有勾选的时候则有重力影响。"

★ 为什么"把重力设成 0"是不够的（本模块存在的唯一理由）：
    重力是**逐帧积分**进去的。你在"掉到一半"时把重力设 0 —— 机械臂就停在半空那个歪姿上，
    各关节还带着速度继续滑。要的是"**回到默认姿态并定住**"，所以必须两件事一起做：
        ① 数据复位到默认姿态（`mj_resetDataKeyframe(home)`）
        ② **把物理暂停**（官方 `sim.StepControl` 的 `NORMAL_PAUSED`）
    实测（本机 UR5e）：暂停后连打 500 次 `advance()`，`qpos` 变化 **0.0** —— 真的冻住。

★ 架构上为什么写成"仿真侧插件"（而不是改 `启动.py`）：
    外壳 3 个核心文件被 `零改动自检.py` 用哈希钉住（契约：**加功能不该改外壳**）。
    塞进 `主程序.py` 的【插件清单】正是契约明确允许的那条路。
    拿不到外壳手里的 `StepControl` 引用怎么办？—— **外壳把它作为第 0 个插件注册**，
    而 `插件系统.安全注册表` 在构造时就是 `[StepControl(), *用户插件]`，
    所以插件只要声明 `绑定步进(...)`，`通知模型加载` 就会把**同一个 StepControl 对象**交给它。
    （这条挂钩用的是外壳现成的"给插件发模型"机制，不需要改外壳一行。）

★ 两者会打架吗？不会，靠**优先级**解决：
    官方 ViewerApp 每帧发一条 `StepControlSnapshot(pause_state=用户在官方面板上的选择)`，
    它会被官方 StepControl 收下并 apply。所以我的插件**也在模型加载后把暂停状态重新设回去**，
    并且每步都再确认一次 —— 结果：
        · 用户没碰官方面板暂停键 → 快照每帧都是 UNPAUSED，我会在每步把它拉回 PAUSED，展示姿态保持
        · 用户自己按了官方暂停键   → 我把那个意图记下来，取消勾选时恢复成"用户想要的"状态
"""
from __future__ import annotations

import dataclasses

import mujoco

from mujoco.experimental.studio import messages, sim


# ---------------------------------------------------------------------------
# 界面 → 仿真侧的消息
# ---------------------------------------------------------------------------
@dataclasses.dataclass(frozen=True)
class 关重力状态(messages.Snapshot):
    """要不要按"无重力的展示姿态"定住。

    ★ 必须是 @dataclasses.dataclass，否则 pybind 侧的字段访问拿不到值
      （和 `界面桥.面板目标消息` 同一个坑，实测踩过）。
    """

    关闭: bool = False


# ---------------------------------------------------------------------------
# ★ 仿真侧插件（`展示姿态插件`）已经搬到 `算法库/通用/展示姿态.py`
# ---------------------------------------------------------------------------
# 为什么搬：方案 C 之后"控制算法"统一由 `项目/*.json` 声明、从 `算法库/` 装配，
# 这样才能出现在界面的算法列表里。留在本文件里的插件不属于任何项目，
# 结果就是——勾选框还在，但仿真侧没人接（静默失效）。
#
# 本文件从此刻起只负责两件事（都是"桥"的本职）：
#   ① 消息契约 `关重力状态` —— 界面与算法都必须从这里 import（同一个类对象）
#   ② 发布器 —— 界面把勾选状态发出去
# ---------------------------------------------------------------------------
# ---------------------------------------------------------------------------
# 发布器：界面把勾选状态发给仿真侧（只在变化 / 到时限时才真发）
# ---------------------------------------------------------------------------
class 发布器:
    """把【Display】的勾选状态发给仿真侧。

    ★ 用 `Snapshot`（最新覆盖）语义 —— 界面每帧覆盖一次，所以**万一两边状态不同步
      （比如用户又去点了官方 Simulation 面板的暂停），下一帧就会被勾选框纠正回来**。
    """

    def __init__(self, 发送函数, 频率: float = 10.0):
        self._发 = 发送函数
        self._间隔 = 1.0 / max(频率, 1e-6)
        self._上次时间 = 0.0
        self._上次值 = None

    def 也许发布(self, 关闭: bool, 墙钟: float) -> None:
        if 关闭 == self._上次值 and (墙钟 - self._上次时间) < self._间隔:
            return
        self._上次时间, self._上次值 = 墙钟, 关闭
        try:
            self._发(关重力状态(关闭=关闭))
        except Exception:                                                # noqa: BLE001
            pass                     # 这条通道坏了绝不能影响窗口绘制
