"""
契约.py —— **平台适配层要提供什么**（四个能力 + 一个主循环）

为什么要有一层抽象（而不是到处直接写 PyObjC）：
    `软件/宿主窗口.py` 是 macOS 专属写法（AppKit / NSOpenGLView / WKWebView）。
    它现在能跑，但"能跑"不等于"可移植"——如果入口直接 `import 宿主窗口`，
    那么将来做 Windows 版时，改动会从入口一路扩散进去，谁也不知道边界在哪。

    这层抽象只回答一个问题：**换一个平台，最少要实现什么？**
    答案是五件事，没有第六件：

      ① 建窗口     —— 一个能容纳子视图的顶层窗口
      ② 挂网页     —— 在窗口里放一个 WebView，加载给定地址
      ③ 取视口矩形 —— 原生 3D 渲染面在窗口里占哪块（给"网页让位"用）
      ④ 同级组合   —— 网页与原生渲染面**平级**摆放、一起随窗口缩放
      ⑤ 进主循环   —— 把主线程交给平台的事件循环，直到用户关窗

    ★ 这四个能力正是 P2 spike 验过的"同级视图"所需的最小集合。
      任何平台只要能提供这五件事，界面与 3D 的代码都不用改。

本文件只放**接口与约定**，不放任何平台代码。
"""
from __future__ import annotations

from abc import ABC, abstractmethod
from typing import Any


class 平台能力(ABC):
    """一个平台的窗口实现。子类放在 `软件/平台适配层/<平台名>.py`。"""

    #: 给人看的平台名（诊断输出用）
    名称: str = "未命名"

    # ------------------------------------------------------------------
    @abstractmethod
    def 可用(self) -> tuple[bool, str]:
        """这个平台现在能不能起窗口。返回 (可用?, 不可用时的原因)。

        ★ 必须是"能查的"，不能靠 try/except 猜：入口要在起窗口**之前**
          就知道该不该回退（比如缺 PyObjC 时应该提示装什么，而不是抛一堆栈）。
        """

    @abstractmethod
    def 起(self, *, 地址: str, 标题: str, 宽: float, 高: float,
           命令队列: list | None = None, 无3D: bool = False,
           视口槽: dict | None = None) -> int:
        """起窗口并**阻塞**到用户关窗。返回进程退出码。

        参数
          地址      : WebView 要加载的地址（通常是本机 `http://127.0.0.1:<口>/`）
          标题      : 窗口标题
          宽 / 高   : 初始窗口尺寸（逻辑像素）
          命令队列  : 仿真线程每圈排空的那个队列（宿主侧要往里塞命令）
          无3D      : True 时不要原生渲染面，网页铺满（排查用）
          视口槽    : 可选 dict，平台层**建好原生渲染面后回填**
                      `视口槽["视口"] = <渲染面对象>`。
                      用途：入口把"仿真每步的状态"喂给它（`视口.收_状态`），
                      而不必知道这个渲染面是什么平台的东西 ——
                      **这是平台层与入口之间唯一的状态通道，只有这一个。**

        约定
          · 主线程归平台事件循环；仿真必须在**后台线程**（见 `启动.启动外壳(后台线程=True)`）
          · 不得与仿真共享 `MjData`（跨线程可变对象），只通过状态快照同步
        """

    @abstractmethod
    def 视口矩形(self) -> tuple[int, int, int, int] | None:
        """原生渲染面当前占的矩形 (x, y, 宽, 高)，逻辑像素；没有则 None。

        用途：网页侧需要知道"哪一块被原生面占了"，才不会在那里画东西、
        也才能把浮层排到正确的位置。
        """

    @abstractmethod
    def 统计(self) -> dict:
        """运行统计（帧率、帧数、错误…）。用于自检与排查，**不参与业务**。"""
