"""
观测核心.py —— 病态检出（把"看数"变成"下结论"）

═══ 一句话说明它在解决什么 ════════════════════════════════════════════════
    监控页现在告诉你「误差 = 29.8」——那是**体温计**：给了数，判断留给人。
    这里要变成**监护仪**：看一段时间的**形状**，然后说
    「12.3–14.1 秒，误差以 4.7 Hz 周期性过零、振幅 12°，且不衰减 → 关节在振荡」。

═══ 为什么需要环形缓冲（而不是只看当前值）══════════════════════════════════
    「周期性」「不衰减」「持续超差」都是**一段时间上的性质**。
    只有当前值的话，一条抖动的曲线和一个在爬升的曲线看起来一样。

═══ 判定原则（这几条决定了它有没有用）════════════════════════════════════
    ① **宁可少报，不可乱报**。误报几次之后，人就会开始无视所有告警 ——
       那时这套东西的价值是负的。所以每个判定都要求"样本够多、时间够长"。
    ② **只说有证据的结论**。每条告警都带量化证据（频率/振幅/斜率/时段），
       而不是"看起来不太对"。
    ③ **建议是经验规则，不是自动整定**。界面上要写明这一点。
    ④ **不猜没有的量**。没有热模型就没有温度；没有真机就没有驱动器侧跟随误差。

═══ 现在能检出哪几类 ═════════════════════════════════════════════════════
    振荡 / 发散 / 跟踪超差 / 饱和 —— 这四类都能从现有信号（误差、力矩、
    饱和关节数）上判定。抖动与振荡在频域上重叠，合并进"振荡"，不单列。

    **模型失配**暂时不做：它需要把 `qfrc_bias` 回推的期望加速度与实际加速度
    逐关节对比，那是**逐关节**的量，而当前 `指标()` 只到聚合级（最大值）。
    要做的话得先扩指标 —— 放在后面，不在这里假装能测。
"""
from __future__ import annotations

import dataclasses
import math
from collections import deque
from typing import Any

from 官方层 import messages          # 全部走适配层，见 软件/官方层.py


# ---------------------------------------------------------------------------
# 环形缓冲
# ---------------------------------------------------------------------------
class 环形缓冲:
    """按**时间**存一条信号。容量满了丢最老的。

    ★ 为什么自己写而不用 deque + 遍历：
      判定要反复取"最近 W 秒"的窗口，每秒判定一次。deque 每次都要从头扫，
      而这里用 numpy 数组 + 双指针，取窗口是切片。
      不过为了让代码短、可读，这里用 deque 存 (t, v)，再在取值时转数组 ——
      20 Hz × 60 s = 1200 个点，转换成本可以忽略（实测 < 0.1 ms）。
    """

    def __init__(self, 保留秒: float = 60.0):
        self.保留秒 = float(保留秒)
        self._点: deque[tuple[float, float]] = deque()

    def 记(self, t: float, v: float) -> None:
        if not (isinstance(t, (int, float)) and isinstance(v, (int, float))):
            return
        if not (math.isfinite(t) and math.isfinite(v)):
            return                      # NaN/Inf 不进缓冲：它们会把均值与极值全毁掉
        self._点.append((float(t), float(v)))
        while self._点 and self._点[0][0] < t - self.保留秒:
            self._点.popleft()

    def 取(self, 最近秒: float | None = None) -> tuple[list[float], list[float]]:
        if not self._点:
            return [], []
        if 最近秒 is None:
            ts = [p[0] for p in self._点]
            vs = [p[1] for p in self._点]
            return ts, vs
        截止 = self._点[-1][0] - float(最近秒)
        ts, vs = [], []
        for t, v in self._点:
            if t >= 截止:
                ts.append(t)
                vs.append(v)
        return ts, vs

    def 跨度秒(self) -> float:
        if len(self._点) < 2:
            return 0.0
        return self._点[-1][0] - self._点[0][0]

    def 点数(self) -> int:
        return len(self._点)


# ---------------------------------------------------------------------------
# 告警
# ---------------------------------------------------------------------------
@dataclasses.dataclass
class 告警:
    类型: str                    # 振荡 / 发散 / 跟踪超差 / 饱和
    严重度: str                  # 严重 / 警告
    信号: str                    # 哪个指标（"关节 PD 位置控制·最大误差(deg)"）
    开始秒: float                # 仿真时间
    结束秒: float
    证据: str                    # 一句话的量化证据
    建议: str                    # 经验建议（界面上要标明"不是自动整定"）
    曲线: tuple = ()             # 该时段的抽样曲线（给界面画小图）
    曲线t: tuple = ()
    最后见: float = 0.0          # 墙钟：最后一次仍被判为病态的时间

    def 键(self) -> str:
        return f"{self.类型}|{self.信号}"


@dataclasses.dataclass(frozen=True)
class 告警消息(messages.Snapshot):
    """仿真侧 → 界面：当前**活动**的告警列表。

    ★ 只发"活动"的，不发历史流水：
      流水会无限增长，而且界面要的是"现在有什么问题、怎么办"。
    """
    活动: tuple = ()
    已检出: int = 0


# ---------------------------------------------------------------------------
# 阈值
# ---------------------------------------------------------------------------
# ★ 为什么阈值要写在明处并按信号给：这些数全是**经验值**，
#   换个机器人、换个单位就不成立。所以：
#   ① 按信号名里的关键词匹配（"误差" / "力矩" / "饱和"）；
#   ② 匹配不到的信号**不判定**（而不是拿一个通用阈值乱判）。
#   宁可漏掉一个信号，也不要在没标定的量上瞎报警。
@dataclasses.dataclass(frozen=True)
class 阈值:
    振荡振幅: float              # 峰峰值的一半超过它才算"在振"
    超差均值: float              # 均值超过它算"跟不上"
    发散倍数: float = 2.0        # 窗口内包络涨这么多倍算"在发散"
    # ★ 每个信号**只跑适用的判定器**。这一条是测试逼出来的：
    #   第一版对所有信号跑全部四个判定器，于是「饱和」判定落到了「误差」上 ——
    #   误差 10° 天然 ≥1，被判成"100% 的采样里至少 1 个关节饱和（最多 16 个）"。
    #   这是典型的**看起来很有依据的胡说**，也正是告警系统最不能犯的错。
    判定们: tuple = ("振荡", "发散", "跟踪超差")


阈值表: tuple[tuple[str, 阈值], ...] = (
    # 关节 PD 的误差（度）：正常跟踪误差在 1° 量级；>0.8° 的持续振荡值得看一眼
    ("误差", 阈值(振荡振幅=0.8, 超差均值=5.0)),
    # 力矩峰值（Nm）：这个量本身波动大，阈值给宽一些，只抓明显振荡
    ("力矩", 阈值(振荡振幅=8.0, 超差均值=120.0)),
    # 饱和关节数：只要有一个关节长时间顶在上限就报。
    #   它是个**计数**，只能跑「饱和」这一个判定器（见 阈值.判定们 的说明）
    ("饱和", 阈值(振荡振幅=0.5, 超差均值=0.5, 判定们=("饱和",))),
)


def 取阈值(信号: str) -> 阈值 | None:
    for 关键词, 阈 in 阈值表:
        if 关键词 in 信号:
            return 阈
    return None


# 判定参数（都要求"够长够多"，这是防误报的第一道闸）
最短窗口秒 = 3.0        # 少于这么长的数据不判定
最少样本数 = 30         # 20 Hz 下 3 秒 = 60 个点；30 是下限
振荡最少过零 = 8        # 少于 4 个完整周期不算"振荡"（避免把台阶当振荡）
超差持续秒 = 2.0        # 均值超限要**持续**这么久才算
告警留存秒 = 12.0       # 墙钟：这么久没再被判为病态就自动消失


# ---------------------------------------------------------------------------
# 判定器
# ---------------------------------------------------------------------------
def _均值(vs: list[float]) -> float:
    return sum(vs) / len(vs) if vs else 0.0


def _峰半振幅(vs: list[float]) -> float:
    return (max(vs) - min(vs)) / 2.0 if vs else 0.0


def 判振荡(ts: list[float], vs: list[float], 阈: 阈值) -> dict | None:
    """周期性过零 + 振幅够大 + 不衰减 → 振荡。

    「周期性」用**过零次数**近似，而不是做 FFT：
      · FFT 对不等间隔采样、短窗、有趋势的信号都不稳；
      · 而"来回过零"本身就是振荡最朴素的定义，也最好解释给人听。
    """
    数 = len(vs)
    if 数 < 最少样本数 or 数 < 2:
        return None
    均 = _均值(vs)
    去均值 = [v - 均 for v in vs]
    过零 = 0
    上次符号 = 0
    for v in 去均值:
        if v == 0:
            continue
        符 = 1 if v > 0 else -1
        if 上次符号 and 符 != 上次符号:
            过零 += 1
        上次符号 = 符
    跨度 = max(ts[-1] - ts[0], 1e-9)
    频率 = 过零 / (2.0 * 跨度)
    振幅 = _峰半振幅(vs)
    if 过零 < 振荡最少过零 or 振幅 < 阈.振荡振幅:
        return None
    # 不衰减：后 1/3 的振幅不低于前 1/3 的 70%
    三分 = max(1, 数 // 3)
    前幅 = _峰半振幅(vs[:三分])
    后幅 = _峰半振幅(vs[-三分:])
    if 前幅 > 1e-9 and 后幅 / 前幅 < 0.7:
        return None                     # 在收敛 → 是正常的调节过程，不是病态
    return {
        "频率": 频率, "振幅": 振幅, "过零": 过零,
        "证据": f"{频率:.1f} Hz、振幅 {振幅:.2f}、{过零} 次过零且不衰减",
    }


def 判发散(ts: list[float], vs: list[float], 阈: 阈值) -> dict | None:
    """包络（分箱后的 |v| 最大值）持续上涨 → 发散。"""
    数 = len(vs)
    if 数 < 最少样本数:
        return None
    # 分 4 箱取每箱 |v| 最大值，作为"包络"
    箱数 = 4
    箱长 = max(1, 数 // 箱数)
    包络 = []
    for i in range(箱数):
        块 = vs[i * 箱长:(i + 1) * 箱长] if i < 箱数 - 1 else vs[i * 箱长:]
        if 块:
            包络.append(max(abs(v) for v in 块))
    if len(包络) < 3:
        return None
    涨 = 包络[-1] / max(包络[0], 1e-9)
    if 涨 < 阈.发散倍数:
        return None
    # 再要求**单调**：至少 3 段里逐段不降（允许一点抖动）
    单调 = sum(1 for a, b in zip(包络, 包络[1:]) if b >= a * 0.98)
    if 单调 < len(包络) - 1:
        return None
    return {"倍数": 涨, "证据": f"包络在窗口内涨了 {涨:.1f} 倍且逐段上升"}


def 判超差(ts: list[float], vs: list[float], 阈: 阈值) -> dict | None:
    """均值超限且持续够久 → 跟踪超差。"""
    if len(vs) < 最少样本数:
        return None
    均 = _均值([abs(v) for v in vs])
    if 均 < 阈.超差均值:
        return None
    if ts[-1] - ts[0] < 超差持续秒:
        return None
    return {"均值": 均, "证据": f"{ts[-1] - ts[0]:.1f} 秒内均值 {均:.2f}（阈值 {阈.超差均值:g}）"}


def 判饱和(ts: list[float], vs: list[float], 阈: 阈值) -> dict | None:
    """饱和关节数长时间 ≥1 → 饱和。"""
    if len(vs) < 最少样本数:
        return None
    有 = [v for v in vs if v >= 1]
    if not 有:
        return None
    占比 = len(有) / len(vs)
    if 占比 < 0.6:                      # 偶尔顶一下不算，要"长期顶着"
        return None
    最多 = max(有)
    return {"占比": 占比, "证据": f"{占比 * 100:.0f}% 的采样里至少 1 个关节顶在上限（最多 {最多:.0f} 个）"}


判定器们 = (
    ("振荡", 判振荡, "警告",
     "先降增益（KP 降一半），再考虑提高阻尼（KD）。振荡是增益过高最典型的表现。"),
    ("发散", 判发散, "严重",
     "立刻停止：误差在放大，继续跑会撞限位。检查符号（正反馈）与目标是否越界。"),
    ("跟踪超差", 判超差, "警告",
     "增益不够或目标变化太快。先看目标轨迹的加速度是否超出机器人能力。"),
    ("饱和", 判饱和, "严重",
     "执行器已经到极限，继续加增益不会有任何改善。降目标速度/加速度，或换更大的执行器。"),
)


# ---------------------------------------------------------------------------
# 观测核心
# ---------------------------------------------------------------------------
class 观测核心:
    """喂数据 → 出告警。

    用法（外壳里）：
        核心 = 观测核心(发送函数)
        每帧:  核心.记录(仿真时间, 指标发布.最近)      # 只在指标真的刷新时
        定时:  核心.判定(仿真时间, 墙钟)               # 内部 1 Hz 节流
    """

    def __init__(self, 发送函数, 保留秒: float = 60.0, 判定间隔: float = 1.0):
        self._发送 = 发送函数
        self._缓冲: dict[str, 环形缓冲] = {}
        self._保留秒 = float(保留秒)
        self._判定间隔 = float(判定间隔)
        self._下次 = 0.0
        self._活动: dict[str, 告警] = {}
        self._上次仿真时间 = 0.0
        self.已判定次数 = 0
        self.已检出 = 0
        self.已发出 = 0

    # ---- 喂 ----
    def 记录(self, 仿真时间: float, 数值: dict[str, Any]) -> None:
        for 名, 值 in (数值 or {}).items():
            try:
                self._缓冲.setdefault(str(名), 环形缓冲(self._保留秒)).记(
                    仿真时间, float(值))
            except (TypeError, ValueError):
                continue            # 非数值指标（字符串状态之类）不参与判定
        self._上次仿真时间 = float(仿真时间)

    # ---- 判 ----
    def 判定(self, 仿真时间: float, 墙钟: float) -> bool:
        if 墙钟 < self._下次:
            return False
        self._下次 = 墙钟 + self._判定间隔
        self.已判定次数 += 1
        现在 = 墙钟

        for 信号, 缓冲 in self._缓冲.items():
            阈 = 取阈值(信号)
            if 阈 is None:
                continue            # 没标定过的量不判定（宁可漏，不乱报）
            if 缓冲.点数() < 最少样本数:
                continue            # 数据还不够，别急着下结论
            ts, vs = 缓冲.取(最近秒=最短窗口秒 if 缓冲.跨度秒() >= 最短窗口秒 else None)
            if len(vs) < 最少样本数:
                continue
            for 类型, 函数, 严重度, 建议 in 判定器们:
                if 类型 not in 阈.判定们:
                    continue            # 这个信号不适用这个判定器（见 阈值.判定们）
                try:
                    果 = 函数(ts, vs, 阈)
                except Exception:                                     # noqa: BLE001
                    continue            # 单个判定器出错不许影响其它判定，更不许影响仿真
                if 果 is None:
                    continue
                键 = f"{类型}|{信号}"
                旧 = self._活动.get(键)
                # ★ 抽样窗口只取**最近 6 秒**，并且最多 60 个点。
                #   第一版取"整段 + 12 个点"：一条 3.7 Hz 的振荡跨 24 秒，
                #   12 个点画出来只有两个起伏 —— 卡片上写"3.7 Hz"、配图却像 0.1 Hz，
                #   图和结论自相矛盾。**配图必须能支撑它旁边的那个数字**。
                视窗 = min(6.0, max(ts[-1] - ts[0], 1e-9))
                截 = ts[-1] - 视窗
                索引 = [i for i, tv in enumerate(ts) if tv >= 截] or [len(ts) - 1]
                长 = max(4, min(60, len(索引)))
                取 = [索引[int(k * (len(索引) - 1) / max(长 - 1, 1))] for k in range(长)]
                新 = 告警(
                    类型=类型, 严重度=严重度, 信号=信号,
                    开始秒=旧.开始秒 if 旧 else ts[0],
                    结束秒=ts[-1],
                    证据=str(果.get("证据", "")),
                    建议=建议,
                    曲线=tuple(round(vs[i], 4) for i in 取),
                    曲线t=tuple(round(ts[i] - ts[0], 3) for i in 取),
                    最后见=现在,
                )
                if 旧 is None:
                    self.已检出 += 1
                    print(f"⚠ 检出【{类型}】{信号}：{新.证据}", flush=True)
                self._活动[键] = 新

        # 过期清理：一段时间没再被判为病态 → 认为已恢复
        死了 = [k for k, a in self._活动.items() if 现在 - a.最后见 > 告警留存秒]
        for k in 死了:
            self._活动.pop(k, None)

        self._发布()
        return True

    def _发布(self) -> None:
        表 = sorted(self._活动.values(), key=lambda a: (a.严重度 != "严重", a.类型))
        try:
            self._发送(告警消息(
                活动=tuple({
                    "类型": a.类型, "严重度": a.严重度, "信号": a.信号,
                    "开始秒": a.开始秒, "结束秒": a.结束秒,
                    "证据": a.证据, "建议": a.建议,
                    "曲线": list(a.曲线), "曲线t": list(a.曲线t),
                } for a in 表),
                已检出=int(self.已检出),
            ))
            self.已发出 += 1
        except Exception:                                             # noqa: BLE001
            pass

    # ---- 给界面/自检用 ----
    def 活动告警(self) -> list[告警]:
        return sorted(self._活动.values(), key=lambda a: (a.严重度 != "严重", a.类型))

    def 清空(self) -> None:
        self._活动.clear()
        self._缓冲.clear()

